export interface IssueRecord {
  /** 全局键 owner/repo#number */
  key: string
  repo: string
  number: number
  title: string
  state: 'OPEN' | 'CLOSED'
  /** closed 骨架：无正文无标签，只为补全父子树 */
  skeleton: boolean
  /** 正文前 500 字（已去 markdown 链接/图片记号），骨架为空串 */
  excerpt: string
  /** 摘要首图的可加载 URL（正文第一张图，已转 raw/直链），无图为 null */
  excerptImage: string | null
  author: string | null
  avatarUrl: string | null
  createdAt: string
  updatedAt: string
  labels: string[]
  url: string
  /** 父 issue 全局键，顶层为 null */
  parentKey: string | null
  /** 父是否在本快照内（closed 父不在，前端升顶层显示） */
  parentAvailable: boolean
  /** 父不在快照时的参考信息 */
  parentHint: { title: string; url: string } | null
  /** GitHub 报的子 issue 总数（含未收录部分） */
  childTotal: number
  /** 本快照内 open 子数 */
  openChildren: number
  /** 本快照内 closed 骨架子数 */
  closedChildren: number
}

